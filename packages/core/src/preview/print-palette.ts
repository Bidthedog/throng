/** The palette as `:root` custom properties, for the printable document's stylesheet. */
export function printPaletteCss(): string {
  const declarations = Object.entries(PRINT_PALETTE).map(([token, value]) => `  --throng-colour-${token}: ${value};`);
  return `:root {\n${declarations.join('\n')}\n}\n`;
}
