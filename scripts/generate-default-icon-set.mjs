#!/usr/bin/env node
/**
 * Spec 069 (research R2, R10): compile the default icon set and the icon sets README into core.
 *
 *   node scripts/generate-default-icon-set.mjs           # write the module
 *   node scripts/generate-default-icon-set.mjs --check   # exit 1 if the checked-in module is stale
 *
 * Reads packages/core/src/icons/default-set/<key>.svg (the vendored, sanitised art) and
 * packages/core/src/icons/icon-sets-README.txt, and writes
 * packages/core/src/icons/default-icon-set.generated.ts. The art then ships inside core's compiled
 * JavaScript and never as loose, editable files (FR-021). The keys come from icon-keys.ts, read as
 * source so the generator needs no build.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ICONS = join(ROOT, 'packages/core/src/icons');
const OUT = join(ICONS, 'default-icon-set.generated.ts');

/** The ordered keys, read from the ICON_KEYS tuple in icon-keys.ts. */
export function readKeys(iconsDir = ICONS) {
  const source = readFileSync(join(iconsDir, 'icon-keys.ts'), 'utf8');
  const tuple = /export const ICON_KEYS = \[([\s\S]*?)\] as const;/.exec(source);
  if (!tuple) throw new Error('icon-keys.ts: ICON_KEYS tuple not found');
  return [...tuple[1].matchAll(/'([A-Za-z0-9]+)'/g)].map((m) => m[1]);
}

/** The module text for the given art directory. Pure, so a test can compare it with the file on disk. */
export function generateModule(iconsDir = ICONS) {
  const keys = readKeys(iconsDir);
  const readme = readFileSync(join(iconsDir, 'icon-sets-README.txt'), 'utf8').replace(/\r\n/g, '\n');
  const entries = keys.map((key) => {
    const svg = readFileSync(join(iconsDir, 'default-set', `${key}.svg`), 'utf8').replace(/\r\n/g, '\n').trim();
    return `  ${key}: ${JSON.stringify(svg)},`;
  });
  return `// GENERATED by scripts/generate-default-icon-set.mjs from src/icons/default-set/*.svg and
// src/icons/icon-sets-README.txt. Do not edit: change the sources and run \`npm run generate:icons\`.
// Art: Lucide ${JSON.parse(readFileSync(join(iconsDir, 'default-set', 'SOURCES.json'), 'utf8')).lucideVersion} (ISC; Feather-derived icons MIT, see default-set/LICENSE) and drawings for throng.
import type { IconKey } from './icon-keys.js';

/** The default icon set (spec 069 FR-001): sanitised SVG markup for every key (FR-004). */
export const DEFAULT_ICON_SET: Readonly<Record<IconKey, string>> = {
${entries.join('\n')}
};

/** The plain-text README written into the user's icon sets folder (FR-023). */
export const ICON_SETS_README: string = ${JSON.stringify(readme)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generateModule();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (current !== text) {
      console.error('generate-default-icon-set: default-icon-set.generated.ts is stale; run npm run generate:icons');
      process.exit(1);
    }
    console.log('generate-default-icon-set: up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`generate-default-icon-set: ${readKeys().length} icons → ${OUT}`);
  }
}
